//! Loader for AOT-compiled HolyC programs.
//!
//! The host compiler `hcc/` turns `apps/*.HC` into flat TempleOS-style `.BIN`
//! blobs (header + code + data, no linker, no relocations: code is generated
//! for its load address). build.sh embeds the blobs into the kernel through
//! `build/hcapps_data.rs`; `Run Name;` copies one into low memory and calls
//! its entry point — ring 0, single address space, exactly like TempleOS.

use crate::term;

/// hcc emits code assuming this load base. The bootloader identity-maps the
/// low 4 GiB with 2 MiB pages, so 0x200000 is directly executable.
const PROG_BASE: usize = 0x200_000;

/// "HC01" little-endian: bytes 48 43 30 31.
const HDR_MAGIC: u32 = 0x3130_4348;

// Generated by build.sh (kept above include! as a plain comment; a doc
// comment on a macro invocation is flagged unused by rustdoc).
include!("../build/hcapps_data.rs");

fn find_blob(name: &str) -> Option<&'static [u8]> {
    let name = name.trim();
    if name.is_empty() {
        return None;
    }
    for (stem, blob) in APPS {
        if stem.eq_ignore_ascii_case(name) {
            return Some(blob);
        }
    }
    None
}

pub fn lookup(name: &str) -> bool {
    find_blob(name).is_some()
}

fn list() {
    if APPS.is_empty() {
        term::set_fg(term::DARK_GRAY);
        term::print_str("  no HolyC apps embedded (put .HC files in apps/)\n");
        term::set_fg(term::theme_fg());
        return;
    }
    for (stem, blob) in APPS {
        term::set_fg(term::LIGHT_GREEN);
        term::print_str(stem);
        term::set_fg(term::DARK_GRAY);
        for _ in 0..(12usize.saturating_sub(stem.len())) {
            term::print_str(" ");
        }
        term::set_fg(term::theme_fg());
        term::print_num(blob.len() as i64);
        term::print_str(" bytes\n");
    }
}

/// `Run;` lists apps, `Run Name;` loads and executes one.
pub fn cmd_run(arg: &str) {
    let arg = arg.trim();
    if arg.is_empty() {
        list();
        return;
    }

    let blob = match find_blob(arg) {
        Some(b) => b,
        None => {
            term::set_fg(term::LIGHT_RED);
            term::print_str("no such HolyC app: ");
            term::print_str(arg);
            term::print_str(" (Run; for the list)\n");
            term::set_fg(term::theme_fg());
            return;
        }
    };

    if blob.len() < 16 {
        term::set_fg(term::LIGHT_RED);
        term::print_str("Run: corrupt blob (short header)\n");
        term::set_fg(term::theme_fg());
        return;
    }
    let magic = u32::from_le_bytes([blob[0], blob[1], blob[2], blob[3]]);
    let entry_off = u32::from_le_bytes([blob[4], blob[5], blob[6], blob[7]]);
    let total_len = u32::from_le_bytes([blob[8], blob[9], blob[10], blob[11]]);
    let data_off = u32::from_le_bytes([blob[12], blob[13], blob[14], blob[15]]);

    if magic != HDR_MAGIC
        || total_len != blob.len() as u32
        || data_off < 16
        || data_off > total_len
        || entry_off < 16
        || entry_off >= data_off
    {
        term::set_fg(term::LIGHT_RED);
        term::print_str("Run: bad HC01 header\n");
        term::set_fg(term::theme_fg());
        return;
    }

    unsafe {
        // Copy code + data (string literals, zero-init globals) into place.
        core::ptr::copy_nonoverlapping(blob.as_ptr(), PROG_BASE as *mut u8, blob.len());
        let entry: extern "C" fn() -> i64 =
            core::mem::transmute(PROG_BASE + entry_off as usize);
        entry();
    }

    // The app scribbled all over the framebuffer; bring the shell back.
    term::draw_chrome();
    term::repaint();
}
